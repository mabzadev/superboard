export function studioI18n(locale: "en" | "fr") {
	const messages =
		locale === "fr"
			? french
			: {
					...Object.fromEntries(Object.keys(french).map((key) => [key, key])),
					heading: "Heading",
					text: "Text",
					image: "Image",
					button: "Button",
					divider: "Divider",
					spacer: "Spacer",
					columns: "Columns",
					approved: "Ready",
					draft: "Draft",
					needs_review: "Needs review",
					authentication: "Account access",
					billing: "Billing",
					notification: "Product notification",
					lifecycle: "Lifecycle",
					campaign: "Marketing campaign",
					support: "Support",
					operator: "Team alert",
					messages: "Messages",
					sent: "Sent",
					delivered: "Delivered",
					opens: "Observed opens",
					clicks: "Clicks",
					failed: "Failed",
					legacy: "History",
					unknown: "Not specified",
				};
	const i18n = createFrontI18n({ locale, messages: { [locale]: messages } });
	return (key: string, values?: Record<string, string | number>) =>
		Object.hasOwn(messages, key) ? i18n._(key, values) : key;
}
export function useStudioI18n() {
	const { locale } = useFrontContext();
	return { locale, t: useMemo(() => studioI18n(locale), [locale]) };
}
