export function useSupportI18n() {
	const frontContext = useOptionalFrontContext();
	const locale = frontContext?.locale === "fr" ? "fr" : "en";
	return useMemo(() => {
		const messages = locale === "fr" ? french : {};
		const i18n = createFrontI18n({ locale, messages: { [locale]: messages } });
		return {
			locale,
			t: (key: string, values?: Record<string, string | number>) =>
				i18n._(key, values, { message: key }),
		};
	}, [locale]);
}
