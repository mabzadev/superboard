#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(
  root,
  "sdks/flows/upstream/product/shared/src/basics-v2-components.ts",
);
const cssPath = resolve(
  root,
  "sdks/flows/upstream/packages/styles/src/vars.css",
);
const outputPath = resolve(
  root,
  "workers/flows/src/components/basics-v2.generated.ts",
);
const checkOnly = process.argv.includes("--check");

const keyMap = Object.freeze({
  surveyPopover: "survey-popover",
  checklist: "floating-checklist",
  card: "card",
  tourCard: "tour-card",
  hint: "hint",
  tourHint: "tour-hint",
  modal: "modal",
  tourModal: "tour-modal",
  tooltip: "tooltip",
  tourTooltip: "tour-tooltip",
});

function compileUpstream(source) {
  return ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.ESNext,
      target: ts.ScriptTarget.ES2022,
      verbatimModuleSyntax: true,
    },
    fileName: sourcePath,
    reportDiagnostics: true,
  });
}

function formatGenerated(definitions, cssVariables) {
  const payload = Object.entries(definitions).map(([sourceKey, definition]) => {
    const key = keyMap[sourceKey];
    if (!key) {
      throw new Error(`Unknown Basics V2 definition: ${sourceKey}`);
    }
    return {
      key,
      sourceKey,
      templateType: definition.type,
      icon: definition.icon,
      componentType: definition.componentType,
      name: definition.name,
      description: definition.description,
      slottable: definition.slottable,
      exitNodes: definition.exitNodes ?? [],
      properties: definition.properties,
      cssVariables: Object.fromEntries(cssVariables.map((name) => [name, null])),
    };
  });

  return `/**
 * Generated by scripts/generate-flows-basics-v2.mjs.
 * Source: RBND-studio/flows.sh@fae014730865809c1406726b9d65417ec7155f00
 * Do not edit by hand; use npm run flows-sdk:sync.
 */
export interface FlowBasicsV2ComponentDefinition {
  readonly key: string;
  readonly sourceKey: string;
  readonly templateType: "component" | "tour-component" | "survey-component";
  readonly icon: string;
  readonly componentType: string;
  readonly name: string;
  readonly description: string;
  readonly slottable: boolean;
  readonly exitNodes: readonly string[];
  readonly properties: readonly unknown[];
  readonly cssVariables: Readonly<Record<string, null>>;
}

export const FLOW_BASICS_V2_COMPONENTS = ${JSON.stringify(payload, null, 2)} as const satisfies readonly FlowBasicsV2ComponentDefinition[];
`;
}

const [source, css] = await Promise.all([
  readFile(sourcePath, "utf8"),
  readFile(cssPath, "utf8"),
]);
const compiled = compileUpstream(source);
if (compiled.diagnostics?.some((diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error)) {
  throw new Error("Unable to compile the pinned Basics V2 component definitions");
}
const dataUrl = `data:text/javascript;base64,${Buffer.from(compiled.outputText).toString("base64")}`;
const module = await import(dataUrl);
const cssVariables = [
  ...new Set(
    [...css.matchAll(/(--flows-basicsV2-[A-Za-z0-9-]+)\s*:/g)].map(
      (match) => match[1],
    ),
  ),
];
const generated = formatGenerated(module.BasicsV2Components, cssVariables);

if (checkOnly) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== generated) {
    console.error(
      "Basics V2 generated definitions are stale. Run npm run flows-sdk:sync.",
    );
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, generated, "utf8");
}
