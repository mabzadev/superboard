#!/usr/bin/env node
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { resolveFlutterFlowApplications } from "./flutterflow-application-config.mjs";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const workflowPath = resolve(
  root,
  ".github/workflows/sync-flutterflow-applications.yml",
);

export function flutterFlowApplicationWorkspace(applicationId) {
  if (!/^[a-z][a-z0-9-]*$/u.test(applicationId || "")) {
    throw new Error(
      `Invalid FlutterFlow application id ${String(applicationId)}`,
    );
  }
  return `tools/flutterflow-applications/${applicationId}`;
}

export function renderFlutterFlowApplicationBindings(application) {
  const parameters = new Map(
    application.library.parameters.map((parameter) => [
      parameter.name,
      parameter,
    ]),
  );
  const bindings = Object.entries(application.values).map(([name, value]) => {
    const parameter = parameters.get(name);
    if (!parameter)
      throw new Error(`${application.id} has no ${name} parameter`);
    const environmentSecret = githubEnvironmentSecret(value);
    return {
      name,
      key: parameter.key,
      type: parameter.type,
      value:
        environmentSecret === null
          ? serializeLibraryValue(parameter.type, value)
          : null,
      environmentSecret,
    };
  });
  if (bindings.length !== parameters.size) {
    throw new Error(`${application.id} does not bind every library parameter`);
  }

  const records = bindings
    .map(
      ({ name, key, type, value, environmentSecret }) => `  (
    name: ${dartString(name)},
    key: ${dartString(key)},
    type: ${dartString(type)},
    value: ${value === null ? "null" : dartString(value)},
    environmentSecret: ${environmentSecret === null ? "null" : dartString(environmentSecret)},
  ),`,
    )
    .join("\n");

  return `// Generated by scripts/flutterflow-application-dsl.mjs.
// Source: config/flutterflow-application-bindings.json. Do not edit by hand.

typedef SuperBoardLibraryBinding =
    ({
      String name,
      String key,
      String type,
      String? value,
      String? environmentSecret,
    });

const superBoardApplicationId = ${dartString(application.id)};
const superBoardApplicationDisplayName = ${dartString(application.displayName)};
const superBoardApplicationEnvironment = ${dartString(application.environment)};

const superBoardLibraryBindings = <SuperBoardLibraryBinding>[
${records}
];
`;
}

export function flutterFlowApplicationMatrix(output) {
  return {
    include: output.applications.map((application) => ({
      id: application.id,
      githubEnvironment: application.remoteProject.githubEnvironment,
      workspace: flutterFlowApplicationWorkspace(application.id),
    })),
  };
}

export async function validateFlutterFlowApplicationWorkspaces({
  output = null,
  read = readFile,
} = {}) {
  const resolved = output ?? (await resolveFlutterFlowApplications());
  const errors = [];
  for (const application of resolved.applications) {
    const workspace = flutterFlowApplicationWorkspace(application.id);
    const expected = renderFlutterFlowApplicationBindings(application);
    const files = {
      bindings: `${workspace}/generated/application_bindings.dart`,
      dsl: `${workspace}/dsl/edit.dart`,
      migration: `${workspace}/dsl/migration.dart`,
      test: `${workspace}/test/app_test.dart`,
      pubspec: `${workspace}/pubspec.yaml`,
      readme: `${workspace}/README.md`,
      sourceSnapshot: application.sourceSnapshot,
    };
    const loaded = {};
    for (const [kind, path] of Object.entries(files)) {
      try {
        loaded[kind] = await read(resolve(root, path), "utf8");
      } catch (error) {
        errors.push(
          `${application.id} ${path} is unavailable: ${error.message}`,
        );
      }
    }
    if (loaded.bindings !== undefined && loaded.bindings !== expected) {
      errors.push(
        `${application.id} generated bindings are stale; run npm run flutterflow-applications:generate-dsl`,
      );
    }
    if (loaded.dsl !== undefined) {
      for (const value of [
        "FF_LIBRARY_PROJECT_ID",
        "FF_LIBRARY_SUPERBOARD_ONBOARDING_PAGE_KEY",
        "setLibraryValue(",
        "buildApplicationConfigurationFor",
      ]) {
        if (!loaded.dsl.includes(value)) {
          errors.push(`${application.id} DSL is missing ${value}`);
        }
      }
      if (!loaded.dsl.includes("migrateVocoStarToSuperBoard")) {
        errors.push(
          `${application.id} DSL does not invoke its brownfield migration`,
        );
      }
      const forbidden = [
        application.remoteProject.apiKeySecret,
        "open-grow-private-4m5us1",
      ];
      for (const value of forbidden) {
        if (loaded.dsl.includes(value)) {
          errors.push(`${application.id} DSL hardcodes ${value}`);
        }
      }
    }
    if (loaded.migration !== undefined) {
      for (const value of [
        "migrateVocoStarProject",
        "superboardApplicationRestoreSessionJson",
        "superboardApplicationUploadFileJson",
        "superboardApplicationCreateCustomJobJson",
        "superboardSupportInitializeAuthenticated",
        "onboardingPageKey",
        "setLibraryPageRoute",
        "getAppOnBording",
      ]) {
        if (!loaded.migration.includes(value)) {
          errors.push(`${application.id} migration is missing ${value}`);
        }
      }
      let forbiddenLiterals = [];
      if (loaded.sourceSnapshot !== undefined) {
        try {
          forbiddenLiterals = sourceForbiddenLiterals(
            JSON.parse(loaded.sourceSnapshot),
          );
        } catch (error) {
          errors.push(
            `${application.id} source snapshot cannot supply convergence literals: ${error.message}`,
          );
        }
      }
      for (const value of forbiddenLiterals) {
        if (loaded.migration.includes(value)) {
          errors.push(
            `${application.id} migration retains forbidden source literal ${value}`,
          );
        }
      }
    }
    if (
      loaded.test !== undefined &&
      !loaded.test.includes("superBoardLibraryBindings")
    ) {
      errors.push(`${application.id} DSL test does not assert every binding`);
    }
  }

  let workflow = "";
  try {
    workflow = await read(workflowPath, "utf8");
  } catch (error) {
    errors.push(
      `FlutterFlow application sync workflow is unavailable: ${error.message}`,
    );
  }
  for (const value of [
    "flutterflow-applications:check",
    "--github-matrix",
    "flutterflow ai test",
    "flutterflow ai run",
    "flutterflow-library-pages.mjs",
    "FF_APPLICATION_PROJECT_ID",
    "FF_LIBRARY_PROJECT_ID",
    "FF_API_KEY",
  ]) {
    if (workflow && !workflow.includes(value)) {
      errors.push(`FlutterFlow application sync workflow is missing ${value}`);
    }
  }
  const testIndex = workflow.indexOf("flutterflow ai test");
  const runIndex = workflow.indexOf("flutterflow ai run");
  if (testIndex >= 0 && runIndex >= 0 && testIndex > runIndex) {
    errors.push(
      "FlutterFlow application sync workflow must test before pushing",
    );
  }

  return {
    schemaVersion: 1,
    status: errors.length === 0 ? "ok" : "blocked",
    applications: resolved.applications.length,
    bindings: resolved.applications.reduce(
      (total, application) => total + Object.keys(application.values).length,
      0,
    ),
    errors,
  };
}

export function sourceForbiddenLiterals(snapshot) {
  const checks = snapshot?.convergence?.checks;
  if (!Array.isArray(checks)) {
    throw new Error("convergence checks are unavailable");
  }
  return [
    ...new Set(
      checks
        .filter(({ kind }) => kind === "literal-absent")
        .map(({ value }) => String(value || "").trim())
        .filter(Boolean),
    ),
  ].sort();
}

function serializeLibraryValue(type, value) {
  if (type === "string" && typeof value === "string") return value;
  if (type === "boolean" && typeof value === "boolean") return String(value);
  if (type === "integer" && Number.isInteger(value)) return String(value);
  throw new Error(`Invalid ${type} FlutterFlow Library Value ${String(value)}`);
}

function githubEnvironmentSecret(value) {
  if (
    value &&
    typeof value === "object" &&
    !Array.isArray(value) &&
    value.source === "github-environment-secret" &&
    /^[A-Z][A-Z0-9_]+$/u.test(value.name || "")
  ) {
    return value.name;
  }
  return null;
}

function dartString(value) {
  return JSON.stringify(String(value));
}

function argument(name) {
  const index = process.argv.indexOf(`--${name}`);
  return index < 0 ? null : process.argv[index + 1] || null;
}

async function main() {
  const output = await resolveFlutterFlowApplications();
  if (process.argv.includes("--github-matrix")) {
    process.stdout.write(
      `${JSON.stringify(flutterFlowApplicationMatrix(output))}\n`,
    );
    return;
  }
  const applicationId = argument("application");
  const applications = applicationId
    ? output.applications.filter(({ id }) => id === applicationId)
    : output.applications;
  if (applicationId && applications.length !== 1) {
    throw new Error(`Unknown FlutterFlow application ${applicationId}`);
  }
  if (process.argv.includes("--write")) {
    for (const application of applications) {
      const path = resolve(
        root,
        flutterFlowApplicationWorkspace(application.id),
        "generated/application_bindings.dart",
      );
      await mkdir(dirname(path), { recursive: true });
      await writeFile(
        path,
        renderFlutterFlowApplicationBindings(application),
        "utf8",
      );
      process.stdout.write(`${path}\n`);
    }
    return;
  }
  const validation = await validateFlutterFlowApplicationWorkspaces({ output });
  process.stdout.write(`${JSON.stringify(validation, null, 2)}\n`);
  if (validation.status !== "ok") process.exitCode = 1;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    await main();
  } catch (error) {
    process.stderr.write(
      `${error instanceof Error ? error.message : String(error)}\n`,
    );
    process.exitCode = 1;
  }
}
